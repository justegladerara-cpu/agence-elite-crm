export function Icon({ n, size = 18, className = '', style }) {
  const d = P[n]
  if (!d) return null
  return (
    <svg className={`ic ${className}`} width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round" style={style} aria-hidden="true">
      <path d={d} />
    </svg>
  )
}

// Titre dont l'emoji de tête est remplacé par une icône
const EMO = {
  '🎯': 'target', '🔁': 'repeat', '🟠': 'bell', '🤝': 'handshake', '🔥': 'flame', '📁': 'folder', '🧪': 'flask', '📞': 'phone',
  '📡': 'radio', '⏰': 'clock', '📅': 'calendar', '🗓': 'calendar', '✉': 'mail', '🚫': 'ban', '🏷': 'tag', '🔍': 'search',
  '🔴': 'alert', '🔻': 'funnel', '📈': 'trend', '💶': 'wallet', '⚡': 'bolt', '🏆': 'trophy',
}
export function withIcon(s) {
  if (typeof s !== 'string') return s
  const m = s.match(/^(\S+)\s+(.*)$/s)
  const k = m && EMO[m[1].replace(/️/g, '')]
  if (!k) return s
  return (
    <>
      <span className="sec-ic">
        <Icon n={k} size={16} />
      </span>
      {m[2]}
    </>
  )
}

// Logo : celui choisi dans Paramètres, sinon le logo officiel Agence Elite (fichiers dans public/)
export function Logo({ size = 40, full = false, dark = true }) {
  const b = getBrand()
  if (full) return <img src={b.logo || '/logo-full.png'} alt={b.nom} className="logo-full" />
  if (b.logo) {
    // Sur fond sombre sans version claire : le logo est posé sur une pastille blanche
    const chip = dark && !b.logoSombre
    return (
      <span className={`logo-perso ${chip ? 'chip' : ''}`} style={{ height: size + (chip ? 6 : 0) }}>
        <img src={dark ? b.logoSombre || b.logo : b.logo} alt={b.nom} />
      </span>
    )
  }
  return <img src={dark ? '/logo-mark-light.png' : '/logo-mark.png'} alt={b.nom} className="logo" style={{ width: size * 1.45, height: 'auto' }} />
}
